import React, { createContext, useContext, useState, useEffect } from 'react';
import { getInitialEvents } from '../data/initialEvents';
import { generateEventPlan } from '../data/templateGenerators';

const EventContext = createContext();

const STORAGE_KEY = 'eventora_ai_events_v2';
const ACTIVE_ID_KEY = 'eventora_ai_active_id_v2';

// Heal previously generated events where tasks were scheduled prior to today
const healLegacyEventDates = (eventList) => {
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  return eventList.map((ev) => {
    if (!ev.date || !Array.isArray(ev.timelineTasks)) return ev;
    const eventDt = new Date(ev.date);
    eventDt.setHours(0, 0, 0, 0);

    // Only heal if the celebration itself is in the future
    if (eventDt < today) return ev;

    let changed = false;
    const healedTasks = ev.timelineTasks.map((t, idx) => {
      if (t.completed || !t.dueDate) return t;
      const due = new Date(t.dueDate);
      due.setHours(0, 0, 0, 0);

      // If an uncompleted task deadline is in the past, reschedule to actionable upcoming date
      if (due < today) {
        changed = true;
        const target = new Date(today);
        const daysUntil = Math.max(1, Math.ceil((eventDt - today) / (1000 * 60 * 60 * 24)));
        const offset = Math.min((idx % 3) + 1, daysUntil);
        target.setDate(today.getDate() + offset);
        const finalDate = target > eventDt ? eventDt : target;
        return {
          ...t,
          dueDate: finalDate.toISOString().split('T')[0],
          priority: 'high',
          phase: t.phase || 'Immediate Action',
          notes: t.notes
            ? `${t.notes} [Rescheduled: milestone was previously overdue]`
            : 'Rescheduled: milestone was previously overdue',
        };
      }
      return t;
    });

    return changed ? { ...ev, timelineTasks: healedTasks } : ev;
  });
};

export const EventProvider = ({ children }) => {
  const [events, setEvents] = useState(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return healLegacyEventDates(parsed);
        }
      }
    } catch (e) {
      console.error('Failed to load events from localStorage:', e);
    }
    return getInitialEvents();
  });

  const [activeEventId, setActiveEventId] = useState(() => {
    try {
      const savedId = localStorage.getItem(ACTIVE_ID_KEY);
      if (savedId) return savedId;
    } catch (e) {
      console.error('Failed to load active event id:', e);
    }
    return 'demo-wedding-1';
  });

  // Sync to localStorage
  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(events));
    } catch (e) {
      console.error('Failed to save events to localStorage:', e);
    }
  }, [events]);

  useEffect(() => {
    try {
      localStorage.setItem(ACTIVE_ID_KEY, activeEventId);
    } catch (e) {
      console.error('Failed to save active id to localStorage:', e);
    }
  }, [activeEventId]);

  // Derived current event
  const activeEvent = events.find((e) => e.id === activeEventId) || events[0] || null;

  // Actions
  const createNewEvent = (formDataOrPlan) => {
    let newPlan;
    if (formDataOrPlan && formDataOrPlan.budgetCategories && formDataOrPlan.timelineTasks) {
      // Pre-generated by Gemini API
      newPlan = { ...formDataOrPlan };
    } else {
      // Fallback local blueprint generator
      newPlan = generateEventPlan(formDataOrPlan);
    }

    // Preserve existing completed task states if re-generating for an existing celebration
    const existingMatch = events.find(
      (e) =>
        e.id === newPlan.id ||
        (e.name.toLowerCase().trim() === newPlan.name.toLowerCase().trim() &&
          e.type === newPlan.type)
    );
    if (existingMatch && Array.isArray(existingMatch.timelineTasks)) {
      const completedTitles = new Set(
        existingMatch.timelineTasks
          .filter((t) => t.completed)
          .map((t) => t.title.toLowerCase().trim())
      );
      newPlan.timelineTasks = (newPlan.timelineTasks || []).map((task) => {
        const tLower = task.title.toLowerCase().trim();
        const isMatch =
          completedTitles.has(tLower) ||
          Array.from(completedTitles).some(
            (ct) => tLower.includes(ct) || ct.includes(tLower)
          );
        return isMatch ? { ...task, completed: true } : task;
      });
    }

    setEvents((prev) => [newPlan, ...prev]);
    setActiveEventId(newPlan.id);
    return newPlan;
  };

  const updateEvent = (eventId, updates) => {
    setEvents((prev) =>
      prev.map((ev) => (ev.id === eventId ? { ...ev, ...updates } : ev))
    );
  };

  const deleteEvent = (eventId) => {
    setEvents((prev) => {
      const filtered = prev.filter((ev) => ev.id !== eventId);
      if (activeEventId === eventId && filtered.length > 0) {
        setActiveEventId(filtered[0].id);
      }
      return filtered;
    });
  };

  const resetToDefaults = () => {
    const defaults = getInitialEvents();
    setEvents(defaults);
    setActiveEventId(defaults[0].id);
  };

  // Budget category updates
  const updateBudgetCategory = (eventId, categoryId, newAllocated) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        const updatedCats = ev.budgetCategories.map((c) =>
          c.id === categoryId ? { ...c, allocated: Number(newAllocated) } : c
        );
        return { ...ev, budgetCategories: updatedCats };
      })
    );
  };

  // Expenses management
  const addExpense = (eventId, expenseData) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        const newExpense = {
          id: `exp-${Date.now()}`,
          date: new Date().toISOString().split('T')[0],
          paidStatus: 'paid',
          notes: '',
          ...expenseData,
          amount: Number(expenseData.amount) || 0,
        };
        return {
          ...ev,
          expenses: [newExpense, ...(ev.expenses || [])],
        };
      })
    );
  };

  const deleteExpense = (eventId, expenseId) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          expenses: (ev.expenses || []).filter((x) => x.id !== expenseId),
        };
      })
    );
  };

  const updateExpense = (eventId, expenseId, updates) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          expenses: (ev.expenses || []).map((x) =>
            x.id === expenseId ? { ...x, ...updates } : x
          ),
        };
      })
    );
  };

  // Timeline tasks management
  const toggleTask = (eventId, taskId) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          timelineTasks: (ev.timelineTasks || []).map((t) =>
            t.id === taskId ? { ...t, completed: !t.completed } : t
          ),
        };
      })
    );
  };

  const addTask = (eventId, taskData) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        const newTask = {
          id: `task-${Date.now()}`,
          phase: '1-2 Months Before',
          category: 'General',
          priority: 'medium',
          completed: false,
          notes: '',
          ...taskData,
        };
        return {
          ...ev,
          timelineTasks: [...(ev.timelineTasks || []), newTask],
        };
      })
    );
  };

  const deleteTask = (eventId, taskId) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          timelineTasks: (ev.timelineTasks || []).filter((t) => t.id !== taskId),
        };
      })
    );
  };

  // Vendor checklist management
  const updateVendor = (eventId, vendorId, updates) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          vendors: (ev.vendors || []).map((v) =>
            v.id === vendorId ? { ...v, ...updates } : v
          ),
        };
      })
    );
  };

  const addVendor = (eventId, vendorData) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        const newVendor = {
          id: `vend-${Date.now()}`,
          status: 'Researching',
          contactPerson: '',
          phone: '',
          email: '',
          notes: '',
          ...vendorData,
          estimatedCost: Number(vendorData.estimatedCost) || 0,
          depositPaid: Number(vendorData.depositPaid) || 0,
        };
        return {
          ...ev,
          vendors: [...(ev.vendors || []), newVendor],
        };
      })
    );
  };

  const deleteVendor = (eventId, vendorId) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          vendors: (ev.vendors || []).filter((v) => v.id !== vendorId),
        };
      })
    );
  };

  // AI ideas management
  const toggleIdeaFavorite = (eventId, ideaId) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        return {
          ...ev,
          aiIdeas: (ev.aiIdeas || []).map((i) =>
            i.id === ideaId ? { ...i, favorite: !i.favorite } : i
          ),
        };
      })
    );
  };

  const addCustomIdea = (eventId, ideaData) => {
    setEvents((prev) =>
      prev.map((ev) => {
        if (ev.id !== eventId) return ev;
        const newIdea = {
          id: `idea-${Date.now()}`,
          favorite: true,
          costImpact: 'Moderate',
          ...ideaData,
        };
        return {
          ...ev,
          aiIdeas: [newIdea, ...(ev.aiIdeas || [])],
        };
      })
    );
  };

  return (
    <EventContext.Provider
      value={{
        events,
        activeEventId,
        activeEvent,
        setActiveEventId,
        createNewEvent,
        updateEvent,
        deleteEvent,
        resetToDefaults,
        updateBudgetCategory,
        addExpense,
        deleteExpense,
        updateExpense,
        toggleTask,
        addTask,
        deleteTask,
        updateVendor,
        addVendor,
        deleteVendor,
        toggleIdeaFavorite,
        addCustomIdea,
      }}
    >
      {children}
    </EventContext.Provider>
  );
};

export const useEvents = () => {
  const context = useContext(EventContext);
  if (!context) {
    throw new Error('useEvents must be used within an EventProvider');
  }
  return context;
};
